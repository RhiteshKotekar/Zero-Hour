"""Run Experiment C (+ missing-evidence and replay controls) and write the security results.

    python scripts/run_experiment_c.py [--config config/security_policy.yaml] [--out artifacts/experiments]
                                       [--doc docs/RESULTS_SECURITY.md]

Writes ``experiment_c.json`` and ``experiment_c.csv`` under ``--out`` (gitignored)
and regenerates ``docs/RESULTS_SECURITY.md`` from the measured values only.
"""

from __future__ import annotations

import argparse
import csv
import json
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

from samg.evaluation.experiment_c import load_experiment_c, run_experiment_c

ROOT = Path(__file__).resolve().parents[1]


def _git_rev() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True,
                              check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def _f(x: float | None, nd: int = 3) -> str:
    return "—" if x is None else f"{x:.{nd}f}"


def _ci(s: dict[str, Any]) -> str:
    if s["mean"] is None:
        return "—"
    ci = "" if s["ci95_low"] is None else f" [{_f(s['ci95_low'])}, {_f(s['ci95_high'])}]"
    return f"{_f(s['mean'])}{ci} (n={s['n']})"


def _frac(a: int, b: int) -> str:
    return f"{a} / {b}" + (f" ({a / b:.1%})" if b else "")


def _max_div(level: dict, pair: str, key: str) -> float:
    return max(v[key] for v in level["divergence"][pair].values())


def csv_rows(res: dict[str, Any]) -> list[dict[str, Any]]:
    rows = []
    for lv in res["levels"]:
        for name in ("S1", "S2", "R"):
            c = lv["counts"][name]
            rw = lv["followup"]["reward"][name]
            sh = lv["followup"]["selection_shift"][name]
            pair = {"S1": "S1_vs_R", "S2": "S2_vs_R", "R": None}[name]
            rows.append({
                "corruption_level": lv["corruption_level"], "learner": name,
                "missions": c["missions"], "attacked_missions": c["attacked_missions"],
                "unsupported_submitted": c.get("unsupported_submitted", 0),
                "unsupported_authenticated": c.get("unsupported_authenticated", 0),
                "unsupported_admitted": c["unsupported_admitted"],
                "legit_submitted": c.get("legit_submitted", 0), "legit_blocked": c["legit_blocked"],
                "legit_provisional": c.get("legit_provisional", 0), "frr": c["frr"],
                "updates_applied": c["updates_applied"], "manipulated_updates": c["manipulated_updates"],
                "max_A_fro_vs_R": _max_div(lv, pair, "A_fro") if pair else 0.0,
                "max_theta_l2_vs_R": _max_div(lv, pair, "theta_l2") if pair else 0.0,
                "followup_n": rw["n"], "followup_reward_mean": rw["mean"],
                "followup_reward_ci_low": rw["ci95_low"], "followup_reward_ci_high": rw["ci95_high"],
                "selection_changed_vs_R": sh["changed_vs_reference"], "chose_preferred": sh["chose_preferred"],
            })
    return rows


def render(res: dict[str, Any], runtime_s: float, rev: str) -> str:
    cfg = res["config"]
    levels = res["levels"]
    top = levels[-1]
    n_follow = len(res["seeds"]["followup"])
    pref = cfg["preferred_topology"]
    out: list[str] = []
    w = out.append
    w("# Security results — Experiment C (signed false reports), missing evidence, replay")
    w("")
    w("_Generated by `scripts/run_experiment_c.py`; every number below is measured from that run. "
      "Do not edit by hand — rerun the script._")
    w("")
    w(f"- Code version: `{rev}`; harness `{res['version']}`; allocation solver: `{res['allocation_solver']}`; "
      f"runtime {runtime_s:.0f} s.")
    w(f"- **Frozen attack config hash: `{res['frozen_attack_hash']}`** (frozen after dev-seed tuning, before the "
      "recorded run). Attack: compromised authorised agent "
      f"`{cfg['compromised_agent']}`, preferred topology `{pref}`, inflation +{cfg['inflation']}, "
      f"deflation −{cfg['deflation']}.")
    w(f"- Streams (disjoint seeds from `seed_splits({cfg['master_seed']}, …)`): warm-up {len(res['seeds']['warmup'])} "
      f"training missions; tuning {len(res['seeds']['dev_attack'])} dev attack + {len(res['seeds']['dev_followup'])} "
      f"dev follow-up missions; recorded {len(res['seeds']['attack'])} test attack-phase missions + {n_follow} "
      f"clean test follow-up missions; {len(res['seeds']['missing_evidence'])} test missions for missing evidence.")
    w("- Corruption level = fraction of attack-phase missions in which the compromised agent lies. It is a "
      "**scenario configuration**, chosen by a seeded schedule (nested across levels), not a measured rate.")
    w("- S1 = `VulnerableLinUCB` (signature, role and freshness kept; no evidence gate; learns the agent-claimed "
      "reward). S2 = protected LinUCB behind the full ACP. R = protected LinUCB on the same stream with no attack. "
      "All three start from one saved pre-attack state; follow-up choices are made by frozen copies.")
    w("")
    w("## Security comparison (brief §12.11)")
    w("")
    for lv in levels:
        c1, c2 = lv["counts"]["S1"], lv["counts"]["S2"]
        f = lv["followup"]
        w(f"### Corruption level {lv['corruption_level']:.0%} — {c1['attacked_missions']} of {c1['missions']} "
          "attack-phase missions attacked")
        w("")
        w("| Measure | S1 Vulnerable | S2 Protected |")
        w("|---|---:|---:|")
        w(f"| Unsupported reports submitted (all validly signed; authenticated) | {c1.get('unsupported_submitted', 0)} "
          f"({c1.get('unsupported_authenticated', 0)} auth.) | {c2.get('unsupported_submitted', 0)} "
          f"({c2.get('unsupported_authenticated', 0)} auth.) |")
        w(f"| Unsupported reports admitted to learning | {_frac(c1['unsupported_admitted'], c1.get('unsupported_submitted', 0))} "
          f"| {_frac(c2['unsupported_admitted'], c2.get('unsupported_submitted', 0))} |")
        w(f"| Legitimate reports submitted | {c1.get('legit_submitted', 0)} | {c2.get('legit_submitted', 0)} |")
        w(f"| Legitimate reports incorrectly blocked (FRR) | {_frac(c1['legit_blocked'], c1.get('legit_submitted', 0))} "
          f"| {_frac(c2['legit_blocked'], c2.get('legit_submitted', 0))} |")
        w(f"| Policy updates from unsupported reports (applied update ≠ ground truth) | "
          f"{_frac(c1['manipulated_updates'], c1['updates_applied'])} | "
          f"{_frac(c2['manipulated_updates'], c2['updates_applied'])} |")
        w(f"| Subsequent held-out reward, mean [95% CI] (R = {_ci(f['reward']['R'])}) | {_ci(f['reward']['S1'])} "
          f"| {_ci(f['reward']['S2'])} |")
        p1, p2 = f["paired"]["S1_minus_R"], f["paired"]["S2_minus_R"]
        w(f"| Paired reward difference vs R, mean [95% CI] | {_f(p1['mean_diff'])} [{_f(p1['ci95_low'])}, "
          f"{_f(p1['ci95_high'])}] | {_f(p2['mean_diff'])} [{_f(p2['ci95_low'])}, {_f(p2['ci95_high'])}] |")
        s1, s2 = f["selection_shift"]["S1"], f["selection_shift"]["S2"]
        w(f"| Topology-selection shift vs R (same {s1['n']} follow-up contexts) | "
          f"{_frac(s1['changed_vs_reference'], s1['n'])} | {_frac(s2['changed_vs_reference'], s2['n'])} |")
        w(f"| Follow-up choices of preferred `{pref}` (R: {f['selection_shift']['R']['chose_preferred']}) | "
          f"{s1['chose_preferred']} / {s1['n']} | {s2['chose_preferred']} / {s2['n']} |")
        w(f"| max over arms ‖A − A_R‖_F / ‖θ − θ_R‖₂ | {_f(_max_div(lv, 'S1_vs_R', 'A_fro'))} / "
          f"{_f(_max_div(lv, 'S1_vs_R', 'theta_l2'))} | {_f(_max_div(lv, 'S2_vs_R', 'A_fro'))} / "
          f"{_f(_max_div(lv, 'S2_vs_R', 'theta_l2'))} |")
        w(f"| S2 A/b byte-identical to R | — | {all(lv['s2_state_equals_reference'].values())} |")
        w("")
        types = {k[len("unsupported_type_"):]: v for k, v in c2.items() if k.startswith("unsupported_type_")}
        if types:
            w("Unsupported reports by type (S2 world): " + ", ".join(f"`{k}` = {v}" for k, v in sorted(types.items()))
              + ".")
            w("")
    w("Definitions. *Unsupported* = oracle-labelled false claim (inflated/deflated `REWARD_CLAIM`, or a "
      "`TASK_COMPLETE_CLAIM` for a task that really failed). *Admitted to learning*: S1 — authenticated in an "
      "episode whose applied update used the agent-claimed reward (S1 has no evidence gate); S2 — final status "
      "CORROBORATED in an applied episode. *Incorrectly blocked*: S1 — refused at authentication/freshness, its only "
      "gate; S2 — final status REJECTED/STALE/DUPLICATE/DISPUTED (PROVISIONAL counted separately). *Policy update "
      "from unsupported report*: applied update whose learned reward differs from simulator ground truth by >1e-6. "
      "S1's A-matrix can also differ from R only because it chose different arms during the attack phase.")
    w("")
    w("### Per-arm state divergence at the highest corruption level")
    w("")
    w("| Arm | ‖A_S1−A_R‖_F | ‖θ_S1−θ_R‖₂ | ‖A_S2−A_R‖_F | ‖θ_S2−θ_R‖₂ | ‖A_S1−A_S2‖_F | ‖θ_S1−θ_S2‖₂ |")
    w("|---|---:|---:|---:|---:|---:|---:|")
    for arm, v in top["divergence"]["S1_vs_R"].items():
        v2, v12 = top["divergence"]["S2_vs_R"][arm], top["divergence"]["S1_vs_S2"][arm]
        w(f"| {arm} | {_f(v['A_fro'])} | {_f(v['theta_l2'])} | {_f(v2['A_fro'])} | {_f(v2['theta_l2'])} | "
          f"{_f(v12['A_fro'])} | {_f(v12['theta_l2'])} |")
    w("")
    w(f"Attack-phase topology choices at {top['corruption_level']:.0%}: "
      + "; ".join(f"{k}: {v}" for k, v in top["attack_phase_choices"].items()) + ".")
    w("")
    w(f"### Reason-code counts at {top['corruption_level']:.0%} (agent reports, final status:reason; episodes)")
    w("")
    w("| Code | S1 world | S2 world |")
    w("|---|---:|---:|")
    r1, r2 = top["counts"]["S1"]["reason_codes"], top["counts"]["S2"]["reason_codes"]
    for k in sorted(set(r1) | set(r2)):
        w(f"| `{k}` | {r1.get(k, 0)} | {r2.get(k, 0)} |")
    w("")
    w("The S1 world runs the same ACP for audit, so its reason codes are recorded too; S1's learner ignores them.")
    w("")
    me = res["missing_evidence"]["counts"]
    w("## Missing-evidence configuration (witness withheld)")
    w("")
    w(f"Clean missions with the entire witness stream withheld: {me.get('missions', 0)}. Episodes PROVISIONAL: "
      f"{me.get('episode_PROVISIONAL', 0)} / {me.get('missions', 0)}. Agent claims PROVISIONAL: "
      f"{me.get('claims_PROVISIONAL', 0)}. **Protected updates applied: {me['protected_updates']}** "
      f"(refused `INELIGIBLE_STATUS`: {me.get('protected_refused_INELIGIBLE_STATUS', 0)}); protected state unchanged: "
      f"{res['missing_evidence']['protected_state_unchanged']}. The vulnerable learner applied "
      f"{me.get('vulnerable_updates', 0)} updates from unwitnessed claims. This is safe non-learning: without "
      "witness evidence the protected learner stops learning rather than trusting claims.")
    w("")
    if res["replay"]:
        rp = res["replay"]["counts"]
        w("## Experiment D — replay")
        w("")
        w("| Test | Events | Outcome (status:reason = count) | Duplicate policy updates |")
        w("|---|---:|---|---:|")
        dup = ", ".join(f"`{k[7:]}` = {v}" for k, v in rp.items() if k.startswith("replay_"))
        obs = ", ".join(f"`{k[9:]}` = {v}" for k, v in rp.items() if k.startswith("obsolete_") and ":" in k)
        relearn = ", ".join(f"`{k}` = {v}" for k, v in rp.items() if k.startswith("relearn_refused_"))
        w(f"| Resubmit accepted signed events to S2's world | {rp.get('replayed_events', 0)} | {dup}; re-offered "
          f"learning event: {relearn} | {rp['duplicate_updates_applied']} |")
        w(f"| Same events after the mission epoch advanced (fresh seen-store) | {rp.get('obsolete_epoch_events', 0)} "
          f"| {obs} | 0 (not offered) |")
        w("")
        w(f"S2 policy state unchanged by replay: {res['replay']['policy_state_unchanged']}. Graph-patch attack: "
          "not run (skipped).")
        w("")
    w("## Attack tuning (dev seeds only)")
    w("")
    t = res["tuning"]
    if t:
        w(f"Predeclared rule: at corruption {max(cfg['corruption_levels']):.0%}, try preferred topologies in order of "
          f"fewest pre-attack dev choices ({', '.join(t['order'])}), magnitudes ascending; stop at the first whose S1 "
          f"dev follow-up selection shift ≥ {cfg['tuning_shift_threshold']}. Pre-attack dev choices: "
          f"{t['pre_attack_dev_choices']}.")
        w("")
        w("| Preferred | Inflation | Deflation | S1 dev shift rate | max ‖θ_S1−θ_R‖₂ |")
        w("|---|---:|---:|---:|---:|")
        for tr in t["trials"]:
            w(f"| {tr['preferred_topology']} | {tr['inflation']} | {tr['deflation']} | {_f(tr['s1_shift_rate'])} | "
              f"{_f(tr['s1_theta_div_max'])} |")
        w("")
        w("Chosen: " + (json.dumps(t["chosen"]) if t["chosen"] else
                        "**none reached the threshold** — the largest magnitude was frozen and reported as is."))
        w("")
    # --- falsification ---
    s1max, s2all = top["counts"]["S1"], [lv["counts"]["S2"] for lv in levels]
    sh1 = top["followup"]["selection_shift"]["S1"]
    state_moved = _max_div(top, "S1_vs_R", "theta_l2") > 1e-6
    poisoned = s1max["manipulated_updates"] > 0 and state_moved
    s2_ok = all(c["unsupported_admitted"] == 0 and c["manipulated_updates"] == 0 for c in s2all)
    s2_blocked = sum(c["legit_blocked"] for c in s2all)
    s2_legit = sum(c.get("legit_submitted", 0) for c in s2all)
    w("## Falsification criteria (brief §12.10, security items)")
    w("")
    w("| Criterion | Verdict | Evidence |")
    w("|---|---|---|")
    w(f"| False report changes S1's policy state or later choices (else no poisoning claim) | "
      f"{'supported' if poisoning_ok(poisoned, sh1) else 'NOT supported'} | at {top['corruption_level']:.0%}: "
      f"{s1max['manipulated_updates']} manipulated updates applied; max ‖θ_S1−θ_R‖₂ = "
      f"{_f(_max_div(top, 'S1_vs_R', 'theta_l2'))}; follow-up choices changed on "
      f"{_frac(sh1['changed_vs_reference'], sh1['n'])} contexts |")
    w(f"| S2 admits no unsupported reward (else the evidence gate failed) | "
      f"{'supported' if s2_ok else 'NOT supported — gate failed'} | unsupported admitted: "
      f"{sum(c['unsupported_admitted'] for c in s2all)} / {sum(c.get('unsupported_submitted', 0) for c in s2all)}; "
      f"manipulated updates: {sum(c['manipulated_updates'] for c in s2all)} (all levels) |")
    w(f"| S2 does not reject many legitimate reports | "
      f"{'supported' if s2_legit and s2_blocked / s2_legit < 0.05 else 'NOT supported — see FRR'} | FRR "
      f"{_frac(s2_blocked, s2_legit)} over all levels |")
    p1 = top["followup"]["paired"]["S1_minus_R"]
    harm = p1["ci95_high"] is not None and p1["ci95_high"] < 0
    w(f"| Poisoning lowers S1's later ground-truth utility (not a §12.10 item; reported so the shift is not "
      f"over-read) | {'supported' if harm else 'NOT supported'} | S1 − R paired reward at "
      f"{top['corruption_level']:.0%}: {_f(p1['mean_diff'])} [{_f(p1['ci95_low'])}, {_f(p1['ci95_high'])}], "
      f"n={p1['n_pairs']} (wins/losses/ties {p1['wins']}/{p1['losses']}/{p1['ties']}) |")
    w("| Witness trust is an explicit assumption, not treated as ground truth silently | supported (disclosed "
      "below) | trust boundary section |")
    w("")
    w("## Trust boundary and limitations")
    w("")
    w("- **The witness is trusted.** It signs simulator task transitions faithfully; the ACP-recomputed reward "
      "equals ground truth because the witness is faithful (D033). A compromised or colluding witness is out of "
      "scope, as is theft of the witness or coordinator private key.")
    w("- The attacker is one authorised agent using its own real key with fresh sequence numbers. Authentication, "
      "authorisation and freshness therefore all pass; only witness corroboration stops the claim. Colluding agents "
      "and Byzantine behaviour beyond false reports are not tested.")
    w("- The protected learner never uses a claimed reward, so the S2 result is partly by construction; what the run "
      "measures is that this holds end to end (persistence, gate, learning events) and what it costs (FRR, "
      "PROVISIONAL episodes when evidence is missing).")
    w("- FRR is measured under a faithful, noise-free witness and integer-millisecond timing, so a 0 FRR is "
      "expected; it says nothing about FRR with a lossy or noisy witness (only the withheld-witness case is "
      "tested, and there the protected learner stops learning).")
    w("- The compromised agent files false completion claims only for its own tasks that really failed; with no "
      "sabotage in this run, the unsupported reports are the type counts listed per level.")
    w("- Follow-up evaluation uses frozen copies (no learning on follow-up missions), so it measures the poisoned "
      "state's decisions, not recovery. Sample sizes are small and shown with every rate.")
    w("- The vulnerable learner's harm is bounded by the reward range [0, 1] and the bandit's ridge prior; a larger "
      "corruption level or magnitude would move it more. Corruption levels are configuration, not rates.")
    w("")
    return "\n".join(out) + "\n"


def poisoning_ok(poisoned: bool, shift: dict[str, Any]) -> bool:
    return poisoned or (shift["changed_vs_reference"] or 0) > 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--config", type=Path, default=None, help="security_policy.yaml with an attack: section")
    ap.add_argument("--out", type=Path, default=ROOT / "artifacts" / "experiments")
    ap.add_argument("--doc", type=Path, default=ROOT / "docs" / "RESULTS_SECURITY.md")
    ap.add_argument("--no-tune", action="store_true", help="skip dev tuning; use the config values as frozen")
    args = ap.parse_args(argv)
    cfg = load_experiment_c(args.config)
    t0 = time.perf_counter()
    res = run_experiment_c(cfg, tune=not args.no_tune, log=lambda s: print(s, file=sys.stderr, flush=True))
    runtime = time.perf_counter() - t0
    rev = _git_rev()
    res["code_version"] = rev
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "experiment_c.json").write_text(json.dumps(res, indent=2, default=str), encoding="utf-8")
    rows = csv_rows(res)
    with (args.out / "experiment_c.csv").open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    args.doc.write_text(render(res, runtime, rev), encoding="utf-8")
    print(f"wrote {args.out / 'experiment_c.json'}, {args.out / 'experiment_c.csv'}, {args.doc}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
